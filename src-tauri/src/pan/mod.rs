    #[test]
    fn peak_offset_is_clamped_down_to_real_available_headroom() {
        // media only slightly wider than canvas: real headroom (0.1) is
        // much smaller than High's own 0.25 target -> the applied peak must
        // be the real headroom, not the raw intensity target.
        let mut t = wide_trigger("c1");
        t.media_width = 2112; // 1920 * 1.1 -> headroom = 0.1
        let kfs = generate_pan_keyframes(&[t], PanIntensity::High);
        assert_eq!(kfs.len(), 2);
        let peak = kfs.iter().map(|k| k.value.abs()).fold(0.0f64, f64::max);
        assert!((peak - 0.1).abs() < 1e-9, "{peak}");
    }

    #[test]
    fn zero_headroom_on_the_triggers_own_axis_produces_no_keyframes_for_it() {
        // media exactly matches canvas width -> zero real headroom on the
        // (horizontal) axis this trigger names -> honestly skipped, not a
        // fabricated zero-length pan.
        let mut t = wide_trigger("c1");
        t.media_width = 1920;
        let kfs = generate_pan_keyframes(&[t], PanIntensity::High);
        assert!(kfs.is_empty());
    }

